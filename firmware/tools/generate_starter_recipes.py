#!/usr/bin/env python3
"""Generate compact, immutable defaults from the attributed PicoPak snapshot."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    recipes = json.loads((ROOT / "data/starter-recipes.json").read_text())["recipes"]
    lines = ["/* Generated by tools/generate_starter_recipes.py. See data/starter-recipes.json",
             " * for pinned provenance and unchanged native machine programs. */"]
    names = sorted({step["name"] for recipe in recipes for step in recipe["steps"]})
    lines += ["static const char *const starter_step_names[] = {",
              "    " + ", ".join(map(json.dumps, names)), "};"]
    for number, recipe in enumerate(recipes):
        assert 0 < len(recipe["id"]) <= 20 and 0 < len(recipe["name"]) <= 31
        assert 0 < len(recipe["steps"]) <= 15
        lines.append(f"static const uint8_t starter_steps_{number}[][5] = {{")
        for step in recipe["steps"]:
            assert 0 < len(step["name"]) <= 21 and 1 <= step["location"] <= 6
            assert step["target_f"] == 0 or 60 <= step["target_f"] <= 212
            assert 0 <= step["minutes"] <= 599 and 0 <= step["drain_minutes"] <= 120
            assert step["minutes"] <= 255
            lines.append("    {%d, %d, %d, %d, %d}," %
                         (names.index(step["name"]), step["location"], step["target_f"],
                          step["minutes"], step["drain_minutes"]))
        lines.append("};")
    lines.append("static const StarterRecipe starter_recipes[] = {")
    for number, recipe in enumerate(recipes):
        lines.append("    {%s, %s, %d, starter_steps_%d}," %
                     (json.dumps(recipe["id"]), json.dumps(recipe["name"]),
                      len(recipe["steps"]), number))
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "src/local_starter_recipes.inc"
    content = render()
    if args.check:
        if not target.exists() or target.read_text() != content:
            parser.error("Starter recipe include is stale; run this script without --check")
    else:
        target.write_text(content)
